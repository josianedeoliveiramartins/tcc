        estudar, debater, dialogar acerca da realidade rural e urbana com
        desenvolvimento sustentável pois compreende a necessidade da pesquisa
        sobre a casa comum, sobre o ecossistema que abriga a vida de toda
        humanidade e da diversidade que se torna indispensável ao equilíbrio
        biológico e permite as vivências e experiências culturais e a noção
        de estética como ação compartilhada, de compromisso coletivo.
    </p>


    <!-- =====================================================
         5. METODOLOGIA
    ====================================================== -->

    <p class="secao">
        5. Metodologia
    </p>


    <p>
        O Projeto Político Pedagógico, Regimento do Colégio e a legislação
        vigente, a saber, a Lei de Diretrizes e Bases da Educação Nacional
        Brasileira, Lei 9394/96, a atual Base Nacional Comum Curricular com
        todas as suas alterações, bem como, as novas propostas de bases comuns
        curriculares para o sistema de ensino brasileiro – documentos iluminadores
        dos Planos de Aulas/Trabalho – indicam a necessidade da relação entre
        os conceitos, os conteúdos, as ideias, desenvolvidas no âmbito do ensino
        formal, com as atitudes e ações do cotidiano dos indivíduos. Neste
        sentido, o projeto que quer significar, neste primeiro momento, a
        preocupação científica das ciências todas – saber complexo – com a vida,
        especificamente, da nossa casa comum, do mundo que compartilhamos,
        o planeta terra. Para esse esforço, empreende algumas ações que,
        neste momento, aparecem como importantes e constituem os passos do projeto.
    </p>


    <ol class="numerados">

        <li>
            Coleta de sementes de palmeiras reais. Germinação, preparo das
            mudas e transplante nos locais já indicados neste projeto;
        </li>

        <li>
            Desenvolvimento das atividades regulares dos Componentes Curriculares,
            nos seus conteúdos, conceitos e informações e esforços de relação dos
            conteúdos do Plano de Aula/Pla no de Trabalho, do Projeto Político
            Pedagógico e Plano Integrado com as questões de racionalidade e
            sentimento – sabedoria – com a vida, a existência, as experiências
            e cotidiano dos indivíd uos na comunidade colegial e territorial,
            especialmente, naquilo que toca a cada indivíduo pelas vias da
            ecologia, da educação e do turismo;
        </li>

        <li>
            Continuidade e ampliação do cuidado com o local em que habitamos
            e convivemos, o mundo compartilhado, através do cultivo de sementes
            de plantas, preparação dos locais de plantio, ação de plantar e
            cuidar do desenvolvimento das plantas cultivadas desde a sementeira;
        </li>

        <li>
            Esforço de apropriação dos sentidos contidos nestas ações, como
            primar pelo desenvolvimento da consciência de compromisso com o
            local, o ambiente – debate ético – e cuidado com a beleza, organização
            e alegria com o local, o ambiente, o meio no qual vivemos – sentido
            estético – com perspectivas de qualificação da existência;
        </li>

        <li>
            Empreendimento de relacionamentos possíveis dos conteúdos das
            ciências, desde a Filosofia, na área das Ciências Humanas, até a
            Química, na área das Ciências Naturais, com as questões pessoais/
            individuais e coletivas/comunitárias com a preocupação de viver
            melhor e preparar o ambiente/o meio, para a satisfação de todos,
            desenvolvendo um sentido histórico-crítico da presença humana no
            mundo e da constituição do mundo que compartilhamos;
        </li>

        <li>
            Atividades: 1º - manejo de sementes para produção de mudas;
            2º - cuidado com as mudas e preparação para o plantio; 3º -
            preparação dos locais para plantio, primeiramente, no passeio
            da via pública citado na sequência; 4º - visita às famílias
            proprietárias dos terrenos com intencionalidade de plantio das
            mudas de palmeiras, consultas e diálogos com a comunidade e as
            instituições reguladoras e normatizadoras das vias públicas;
            5º - colocação de estacas de identificação e proteção em cada
            local de plantio, amarrando-as a hastes e organizando o material
            de modo a proteger as plantas das ações depredadoras e despertando/
            alertando para as alterações no local indicando a ação educativa,
            tanto para quem a realiza quanto para quem visualiza e, com elas,
            convive; 6º - ampliação da ação de plantio, para os locais indicados
            no momento anterior desse projeto.
        </li>

    </ol>


