        que transcenda as salas de aulas e as retóricas e se efetive no
        cotidiano do território, não somente restrito a seu espaço geográfico,
        mas regional, o que significa expressar as relações que esse projeto
        prevê com o município de Novo Tiradentes. Desse modo, ao se referir
        a território, este projeto envolve o município de Cerro Grande e de
        Novo Tiradentes. Tanto na dimensão da educação ecológica, quanto do
        embelezamento, do aprimoramento para a ação turística.
    </p>


    <p>
        Parece que o povo se acomoda em seus costumes e vivências, excluídos
        pela grande mídia e satisfeito com o mínimo que lhes é oferecido.
        A cidadania esvai-se, esfriando a consciência cidadã, a possibilidade
        de crescimento pessoal, coletivo e científico. Os projetos do CEEDO
        têm sido instrumentos potencializadores da necessária e urgente atitude
        despertadora, nas comunidades pequenas e isoladas por questões
        geográficas, econômicas e culturais, e são ações incentivadoras do
        pensamento e de atitudes científicas.
    </p>


    <p>
        O Colégio, centro de cultura nas pequenas comunidades, além de centro
