        científico, criativo e as aproximações teorias e prática, tornando-se
        na área do território, agente de cultura, com reconhecimento comunitário,
        e possibilidade de desenvolver ações de reflexão, participação,
        envolvimento e inclusão da população nos projetos científicos,
        artísticos, teatros, produção de vídeos, filmes curta, fotografias,
        exposições, mostras de cultura e debates, alimentando a consciência,
        a cidadania e espírito comunitário, como passos importantes na
        valorização pessoal e reconhecimento das capacidades e potencialidades pessoais.
    </p>


    <p>
        O Projeto Interinstitucional Palmeiras da história, com educação pela
