          O projeto COOPCEEDO, iniciado em 2022, é uma iniciativa interdisciplinar conduzida por alunos e professores do Colégio Estadual Dr. Dorvalino Luciano de Souza (CEEDO), com o objetivo de integrar práticas pedagógicas e cooperativismo, promovendo a sustentabilidade e a formação integral dos estudantes. Com apoio de instituições como CPM escolar, Emater/RS, Prefeitura de Cerro Grande/RS, Sicredi e Cresol, o projeto visa a permanência e crescimento sustentável da cooperativa, por meio da produção e comercialização de produtos ligados à meliponicultura, reaproveitamento de materiais e educação ambiental. As atividades abrangem desde a produção de caixas para abelhas nativas até a capacitação técnica e financeira dos cooperados, garantindo a aplicação prática dos conhecimentos adquiridos e a promoção de uma gestão transparente e eficiente. A proposta também incentiva a pesquisa de campo, a consciência socioambiental e o desenvolvimento de habilidades profissionais compatíveis com a formação técnica dos alunos.
